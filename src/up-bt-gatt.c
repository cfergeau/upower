static GHashTable *init_gatt_name_hash(void) {
	GHashTable *uuid_descriptions_map;
	unsigned int i;

	uuid_descriptions_map = g_hash_table_new(g_str_hash, g_str_equal);
	for (i = 0; i < G_N_ELEMENTS(gatt_uuid_descriptions); i++) {
		g_hash_table_insert(uuid_descriptions_map,
		                    gatt_uuid_descriptions[i].uuid,
		                    gatt_uuid_descriptions[i].description);
	}

	return uuid_descriptions_map;
}

const char *gatt_attribute_description(const char *uuid) {
	static GOnce uuid_description_once = G_ONCE_INIT;
	GHashTable *uuid_descriptions_map;

	g_once(&uuid_description_once, (GThreadFunc)init_gatt_name_hash, NULL);
	uuid_descriptions_map = uuid_description_once.retval;

	return(g_hash_table_lookup(uuid_descriptions_map, uuid));
}
